#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';

const root = path.resolve(import.meta.dirname, '..');
const userscriptPath = path.join(root, 'PSChina Server Translation SV-1.7.2.txt');
const generatedPath = path.join(root, 'localization', 'generated');
const clientRoot = path.join(root, 'upstream', 'pokemon-showdown-client', 'play.pokemonshowdown.com');
const outputPath = path.join(clientRoot, 'js', 'localization-zh-hans.js');
const preactInitPath = path.join(clientRoot, 'js', 'localization-preact-init.js');

function readJSON(filename) {
	return JSON.parse(fs.readFileSync(filename, 'utf8'));
}

function isOfficial(entry) {
	return entry.nonstandard !== 'CAP' && (entry.num === null || entry.num >= 0);
}

function buildCatalog() {
	const catalog = {};
	for (const category of ['species', 'moves', 'abilities', 'items', 'natures']) {
		const entries = readJSON(path.join(generatedPath, `${category}.json`));
		catalog[category] = Object.fromEntries(entries.filter(isOfficial).map(entry => [entry.id, entry.zhHans]));
	}
	return catalog;
}

function extractDescriptionPrefixes(source) {
	const prefixes = [];
	const rule = /if \(value\.startsWith\(("(?:\\.|[^"\\])*")\)\) node\.nodeValue = ("(?:\\.|[^"\\])*");/g;
	for (const match of source.matchAll(rule)) {
		const english = vm.runInNewContext(match[1]);
		const chinese = vm.runInNewContext(match[2]);
		prefixes.push([english, chinese]);
	}
	return prefixes.sort((a, b) => b[0].length - a[0].length);
}

function extractBattleEngine(source) {
	const start = source.indexOf('var regex_item_was =');
	const end = source.indexOf('function translateNode(node)', start);
	if (start < 0 || end < 0) throw new Error('Could not locate userscript battle translation engine.');
	return source.slice(start, end).trim();
}

const userscript = fs.readFileSync(userscriptPath, 'utf8').replace(/\r\n/g, '\n');
const exact = {
	...readJSON(path.join(generatedPath, 'userscript-dictionary.json')),
	...readJSON(path.join(root, 'localization', 'ui-overrides.zh-Hans.json')),
};
const catalog = buildCatalog();
const prefixes = extractDescriptionPrefixes(userscript);
const battleEngine = extractBattleEngine(userscript);

const runtime = `// DO NOT EDIT - generated by scripts/generate-client-localization.mjs
// Source: PSChina Server Translation SV 1.7.2, PKHeX, and local overrides.
(function (global) {
"use strict";
var translations = ${JSON.stringify(exact)};
var catalog = ${JSON.stringify(catalog)};
var descriptionPrefixes = ${JSON.stringify(prefixes)};

function trans_from_dict(value) {
  return translations[value] || value;
}

${battleEngine}

function preserveWhitespace(original, translated) {
  var leading = original.match(/^\\s*/)[0];
  var trailing = original.match(/\\s*$/)[0];
  return leading + translated + trailing;
}

function translateExact(value) {
  if (typeof value !== 'string' || !value) return value;
  var trimmed = value.trim();
  var translated = translations[trimmed];
  return translated ? preserveWhitespace(value, translated) : value;
}

function translateDescription(value) {
  if (typeof value !== 'string' || !value) return value;
  var exact = translations[value];
  if (exact) return exact;
  for (var i = 0; i < descriptionPrefixes.length; i++) {
    if (value.startsWith(descriptionPrefixes[i][0])) return descriptionPrefixes[i][1];
  }
  return value;
}

function translateBattleText(value) {
  if (typeof value !== 'string' || !value) return value;
  return value.split('\\n').map(function (line) {
    if (!line) return line;
    var leading = line.match(/^\\s*/)[0];
    var core = line.slice(leading.length);
    var translated = translations[core] || core;
    try { translated = t(core); } catch (_) {}
    return leading + (translated || core);
  }).join('\\n');
}

function translateElement(element) {
  if (!element || typeof document === 'undefined') return element;
  var walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT);
  var nodes = [];
  var node;
  while ((node = walker.nextNode())) nodes.push(node);
  if (element.nodeType === Node.TEXT_NODE) nodes.unshift(element);
  for (var i = 0; i < nodes.length; i++) {
    var value = nodes[i].nodeValue || '';
    var translated = translateDescription(value);
    if (translated === value) translated = translateBattleText(value);
    if (translated === value) translated = translateExact(value);
    nodes[i].nodeValue = translated;
  }
  return element;
}

function displayName(category, id, fallback) {
  return (catalog[category] && catalog[category][id]) || translations[fallback] || fallback;
}

var searchRows = [];
var categoryTypes = {species: 'pokemon', moves: 'move', abilities: 'ability', items: 'item'};
Object.keys(categoryTypes).forEach(function (category) {
  Object.keys(catalog[category]).forEach(function (id) {
    searchRows.push({type: categoryTypes[category], id: id, name: catalog[category][id]});
  });
});

function search(query, type) {
  query = String(query || '').trim().toLowerCase();
  if (!query || !/[\\u3400-\\u9fff]/.test(query)) return null;
  var matches = searchRows.filter(function (row) {
    return (!type || row.type === type) && row.name.toLowerCase().includes(query);
  });
  matches.sort(function (a, b) {
    var aExact = a.name.toLowerCase() === query ? 0 : 1;
    var bExact = b.name.toLowerCase() === query ? 0 : 1;
    return aExact - bExact || a.name.length - b.name.length || a.id.localeCompare(b.id);
  });
  return matches.slice(0, 50).map(function (row) { return [row.type, row.id]; });
}

function installPreact(preact) {
  if (!preact || preact.__psZhHansInstalled) return;
  preact.__psZhHansInstalled = true;
  var previous = preact.options.vnode;
  preact.options.vnode = function (vnode) {
    if (previous) previous(vnode);
    var attrs = vnode.attributes || {};
    var className = String(attrs.class || attrs.className || '');
    var protectedText = /(?:^|\\s)(?:username|usernametext|chat|message-log|userlist)(?:\\s|$)/.test(className);
    if (!protectedText && vnode.children) {
      vnode.children = vnode.children.map(function (child) {
        return typeof child === 'string' ? translateExact(child) : child;
      });
    }
    ['placeholder', 'title', 'aria-label'].forEach(function (key) {
      if (typeof attrs[key] === 'string') attrs[key] = translateExact(attrs[key]);
    });
  };
}

global.PSLocalizer = {
  locale: 'zh-Hans',
  catalog: catalog,
  exact: translateExact,
  description: translateDescription,
  battle: translateBattleText,
  element: translateElement,
  name: displayName,
  search: search,
  installPreact: installPreact
};
})(typeof window !== 'undefined' ? window : globalThis);
`;

fs.mkdirSync(path.dirname(outputPath), {recursive: true});
fs.writeFileSync(outputPath, runtime);
fs.writeFileSync(preactInitPath, `/* Generated locale bootstrap: install before panel components are evaluated. */\nif (window.PSLocalizer && window.preact) {\n\twindow.PSLocalizer.installPreact(window.preact);\n}\n`);
console.log(JSON.stringify({
	output: path.relative(root, outputPath),
	preactInit: path.relative(root, preactInitPath),
	exactEntries: Object.keys(exact).length,
	descriptionPrefixRules: prefixes.length,
	battleEngineBytes: Buffer.byteLength(battleEngine),
	catalogEntries: Object.values(catalog).reduce((sum, entries) => sum + Object.keys(entries).length, 0),
}, null, 2));
